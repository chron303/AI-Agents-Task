if __name__ == "__main__":
    print("Copywriting & Ads Agent — Sample Generator")
    try:
        agent = CopywritingAdsAgent()
        info = agent.get_provider_info()
        print(f"\n✓ Connected: {info['provider']} / {info['model']}")
    except EnvironmentError as e:
        print(f"\n✗ {e}")
        sys.exit(1)

